export function categoryLabel(category: OrganismCategory): string {
  switch (category) {
    case 'bird':
      return 'Birds';
    case 'insect':
      return 'Insects';
    case 'plant':
      return 'Plants';
    case 'fungi':
      return 'Fungi';
    case 'reptile':
      return 'Reptiles';
    case 'mammal':
      return 'Mammals';
    case 'amphibian':
      return 'Amphibians';
    case 'aquatic':
      return 'Aquatic';
  }
}
